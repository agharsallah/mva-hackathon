#!/usr/bin/env bash
#
# Profile the gated 85 GB dataset without copying patient data into the repo.
#
#   usage: tools/profile-genomic-data.sh /path/to/mva-data/raw
#
# Two output destinations, and the split is deliberate:
#
#   ressources/data-profile/   COMMITTABLE — headers, contig lists, aggregate counts.
#                              File shape and summary statistics only. No variant
#                              records, no read sequences.
#
#   <DATA_DIR>/../work/        LOCAL ONLY, NEVER COMMITTED — panel VCF extract and a
#                              tiny FASTQ subsample for pipeline smoke tests. These
#                              contain real patient sequence and fall under the DTA.
#
set -euo pipefail

DATA_DIR="${1:?usage: profile-genomic-data.sh /path/to/mva-data/raw}"
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROFILE="$REPO/ressources/data-profile"
WORK="$(cd "$DATA_DIR/.." && pwd)/work"

mkdir -p "$PROFILE" "$WORK"

VCF="$(ls "$DATA_DIR"/*.vcf.gz 2>/dev/null | head -1 || true)"
SAMPLE_ALIAS="PROBAND01"

log() { printf '\n=== %s\n' "$*"; }

# ---------------------------------------------------------------------------
# 0. Preflight
# ---------------------------------------------------------------------------
log "preflight"
missing=()
for t in bcftools; do command -v "$t" >/dev/null || missing+=("$t"); done
if [ ${#missing[@]} -gt 0 ]; then
  echo "missing tools: ${missing[*]}" >&2
  echo "install with: brew install bcftools samtools htslib" >&2
  exit 1
fi
[ -n "$VCF" ] || { echo "no *.vcf.gz found in $DATA_DIR" >&2; exit 1; }

{
  echo "# Dataset manifest"
  echo "# generated by tools/profile-genomic-data.sh"
  echo "# filenames and byte sizes only"
  echo
  printf '%s\t%s\t%s\n' "file" "bytes" "sha256_first_1MB"
  for f in "$DATA_DIR"/*; do
    [ -f "$f" ] || continue
    size=$(wc -c < "$f" | tr -d ' ')
    # Hash of the first MB only: enough to detect a corrupt or truncated download,
    # cheap enough to run on 10 GB files.
    h=$(head -c 1048576 "$f" | shasum -a 256 | cut -d' ' -f1)
    printf '%s\t%s\t%s\n' "$(basename "$f")" "$size" "$h"
  done
} > "$PROFILE/manifest.tsv"
echo "wrote $PROFILE/manifest.tsv"

# ---------------------------------------------------------------------------
# 1. VCF — header, shape, aggregate counts
# ---------------------------------------------------------------------------
log "VCF header (sample name redacted)"
bcftools view -h "$VCF" \
  | awk -v alias="$SAMPLE_ALIAS" '
      /^#CHROM/ { for (i = 10; i <= NF; i++) $i = alias; print; next }
      { print }
    ' OFS='\t' \
  > "$PROFILE/vcf_header.txt"
echo "wrote $PROFILE/vcf_header.txt"

# The three facts that decide the whole plan, pulled out of the header for quick reading.
{
  echo "# VCF key facts"
  echo
  echo "## reference build signals"
  grep -E '^##(reference|contig=<ID=(chr)?1,)' "$PROFILE/vcf_header.txt" | head -5
  echo
  echo "## caller / provenance"
  grep -E '^##(source|GATKCommandLine|DeepVariant|bcftools|fileDate|filedate)' "$PROFILE/vcf_header.txt" | head -20
  echo
  echo "## samples in file (redacted names, count is what matters: 1 = single, 3 = trio)"
  grep '^#CHROM' "$PROFILE/vcf_header.txt" | awk '{print "n_samples=" NF - 9}'
  echo
  echo "## chromosome naming"
  grep -m1 '^##contig' "$PROFILE/vcf_header.txt"
} > "$PROFILE/vcf_key_facts.txt"
echo "wrote $PROFILE/vcf_key_facts.txt"

log "VCF INFO/FORMAT/FILTER field inventory"
grep -E '^##(INFO|FORMAT|FILTER)' "$PROFILE/vcf_header.txt" \
  | sed -E 's/^##([A-Z]+)=<ID=([^,]+).*Description="([^"]*)".*/\1\t\2\t\3/' \
  > "$PROFILE/vcf_fields.tsv"
echo "wrote $PROFILE/vcf_fields.tsv"

log "VCF per-contig record counts (from the .tbi, seconds)"
bcftools index -s "$VCF" > "$PROFILE/vcf_contig_counts.tsv"
echo "wrote $PROFILE/vcf_contig_counts.tsv"

log "bcftools stats (few minutes)"
bcftools stats "$VCF" > "$PROFILE/vcf_stats.txt"
echo "wrote $PROFILE/vcf_stats.txt"

log "FILTER and genotype tallies (one full pass, few minutes)"
bcftools query -f '%FILTER\t[%GT]\n' "$VCF" \
  | awk -F'\t' '
      { filt[$1]++; gt[$2]++; if ($2 ~ /\|/) phased++ ; total++ }
      END {
        print "## FILTER counts"
        for (k in filt) printf "%s\t%d\n", k, filt[k]
        print ""
        print "## genotype counts"
        for (k in gt) printf "%s\t%d\n", k, gt[k]
        print ""
        printf "## phased_records\t%d\n", phased + 0
        printf "## total_records\t%d\n", total
      }
    ' > "$PROFILE/vcf_filter_gt_counts.tsv"
echo "wrote $PROFILE/vcf_filter_gt_counts.tsv"

# ---------------------------------------------------------------------------
# 2. FASTQ — lane structure, read length, estimated depth. No sequence emitted.
# ---------------------------------------------------------------------------
log "FASTQ profile (estimate from a 200 MB compressed slice per file, ~seconds each)"
SLICE=200000000

{
  printf '%s\t%s\t%s\t%s\t%s\t%s\n' \
    "file" "bytes" "read_len" "reads_in_slice" "est_total_reads" "est_gbases"
  for f in "$DATA_DIR"/*.fastq.gz; do
    [ -f "$f" ] || continue
    size=$(wc -c < "$f" | tr -d ' ')

    # Truncated gzip stream: decoder exits nonzero after emitting what it could.
    # That is expected here, so the failure is swallowed on purpose.
    rl=$(head -c 400000 "$f" | gzip -cd 2>/dev/null | sed -n '2p' | tr -d '\n' | wc -c | tr -d ' ' || true)
    n=$(head -c "$SLICE" "$f" | gzip -cd 2>/dev/null | wc -l | tr -d ' ' || true)
    reads_slice=$(( n / 4 ))

    if [ "$reads_slice" -gt 0 ]; then
      est_total=$(( reads_slice * size / SLICE ))
      est_gbases=$(awk -v r="$est_total" -v l="$rl" 'BEGIN { printf "%.1f", r * l / 1e9 }')
    else
      est_total=0; est_gbases=0
    fi
    printf '%s\t%s\t%s\t%s\t%s\t%s\n' \
      "$(basename "$f")" "$size" "$rl" "$reads_slice" "$est_total" "$est_gbases"
  done
} > "$PROFILE/fastq_profile.tsv"

# Coverage rollup: total bases / 3.1 Gb haploid genome.
awk -F'\t' 'NR > 1 { g += $6 } END { printf "est_total_gbases\t%.1f\nest_coverage_x\t%.1f\n", g, g / 3.1 }' \
  "$PROFILE/fastq_profile.tsv" >> "$PROFILE/fastq_profile.tsv"
echo "wrote $PROFILE/fastq_profile.tsv"

log "FASTQ read-name headers (index barcode redacted)"
{
  echo "# first read name per file — instrument, run, flowcell, lane, tile."
  echo "# The sample index barcode is redacted; it identifies the library, not the biology."
  for f in "$DATA_DIR"/*.fastq.gz; do
    [ -f "$f" ] || continue
    hdr=$(head -c 4000 "$f" | gzip -cd 2>/dev/null | sed -n '1p' || true)
    redacted=$(printf '%s' "$hdr" | sed -E 's/ ([12]:[YN]:[0-9]+:).*/ \1<redacted-index>/')
    printf '%s\t%s\n' "$(basename "$f")" "$redacted"
  done
} > "$PROFILE/fastq_read_headers.tsv"
echo "wrote $PROFILE/fastq_read_headers.tsv"

# ---------------------------------------------------------------------------
# 3. LOCAL ONLY — real patient sequence. Written outside the repo on purpose.
# ---------------------------------------------------------------------------
log "MVA panel BED (public gene coordinates, committable)"
python3 "$REPO/tools/mva_panel_bed.py" "$PROFILE/mva_panel_grch38.bed" 20000 \
  || echo "panel BED fetch failed — rerun with network access" >&2

if [ -s "$PROFILE/mva_panel_grch38.bed" ]; then
  log "panel VCF extract -> $WORK (LOCAL ONLY, DO NOT COMMIT)"
  grep -v '^#' "$PROFILE/mva_panel_grch38.bed" | cut -f1-3 > "$WORK/panel.bed"
  bcftools view -R "$WORK/panel.bed" -Oz -o "$WORK/panel_mva.vcf.gz" "$VCF"
  bcftools index -t "$WORK/panel_mva.vcf.gz"
  echo "variants in panel: $(bcftools view -H "$WORK/panel_mva.vcf.gz" | wc -l | tr -d ' ')"

  # Per-gene counts ARE committable — a count is not a record.
  {
    printf '%s\t%s\n' "gene" "n_variants"
    while IFS=$'\t' read -r c s e sym _rest; do
      case "$c" in \#*) continue;; esac
      printf '%s\t%s\n' "$sym" \
        "$(bcftools view -H -r "${c}:$((s + 1))-${e}" "$VCF" 2>/dev/null | wc -l | tr -d ' ')"
    done < "$PROFILE/mva_panel_grch38.bed"
  } > "$PROFILE/panel_variant_counts.tsv"
  echo "wrote $PROFILE/panel_variant_counts.tsv"
fi

log "FASTQ smoke-test subsample -> $WORK (LOCAL ONLY, DO NOT COMMIT)"
mkdir -p "$WORK/smoke"
for f in "$DATA_DIR"/*L001_R[12]_001.fastq.gz; do
  [ -f "$f" ] || continue
  out="$WORK/smoke/$(basename "${f%.fastq.gz}").100k.fastq.gz"
  # 100k reads = 400k lines. Enough to exercise a full align/call pipeline in seconds.
  head -c 60000000 "$f" | gzip -cd 2>/dev/null | head -400000 | gzip > "$out" || true
  echo "  $out"
done

log "done"
echo
echo "COMMITTABLE  -> $PROFILE"
ls -lh "$PROFILE"
echo
echo "LOCAL ONLY   -> $WORK   (contains patient sequence; never commit, delete within 30 days of close)"
ls -lh "$WORK"
