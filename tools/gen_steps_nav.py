"""Generate the research subtree of the app's module manifest from the step maps.

The dashboard's navigation is a static array (``app/src/app/modules/index.ts``) because the
router, the header and the journey footer all read it synchronously. The research steps are
*not* static: they are declared in :mod:`mva.science.steps`, one map per iteration, and the
repository's rule is that declaring a step makes it appear rather than requiring a second
edit somewhere else.

So this tool writes the part of the manifest that follows from the step maps —

    Decide ▸ Track 1 ▸ Iteration 2 ▸ Step 4

— and ``pnpm steps-nav:check`` fails the build when the generated file and the maps drift
apart, the same contract ``tools/gen-dictionary.mjs`` has with ``docs/dictionary.md``.

**What is derived, and from what.** A node's label, title and description all come from the
step map: the iteration's summary is its map module's own docstring line, a step's title and
goal are its :class:`~mva.science.step.Step` fields. Nothing about a step is typed here.

**Which steps get a page.** Track 1's iterations list their research steps, because a step
that argues about an allele carries tables and charts a card cannot hold. Track 2's iterations
do not: each has a single step, shown in full on the iteration's own page, with the drug
evidence itself on ``/track2``. Platform steps (``step-0``) belong to no iteration and are
listed on the iteration page rather than in the navigation.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from mva.science import steps as steps_module
from mva.science.step import PLATFORM, Step

#: The generated navigation subtree, in the manifest's own layer.
OUT = Path("app/src/app/modules/steps.generated.ts")

#: The generated registry of analysis bodies. It lives in ``pages/`` rather than beside the
#: manifest because a page may not import from ``app/`` — the layer rule `pnpm lint`
#: enforces — and this map is a page's business, not the shell's.
OUT_BODIES = Path("app/src/pages/steps/bodies.generated.ts")

#: The rich iteration-2 step bodies that already exist as pages. A step with an entry here
#: renders its record *and* that analysis; a step without one renders its record alone,
#: which is the whole truth about a step whose deep page was never built.
BODIES = {
    "iteration2/step-1": "Step1",
    "iteration2/step-2": "Step2",
    "iteration2/step-3": "Step3",
    "iteration2/step-4": "Step4",
    "iteration2/step-5": "Step5",
    "iteration2/step-6": "Step6",
    "iteration2/step-8": "Step8",
}

#: The two tracks, as the navigation names them, and which step tracks each one collects.
#: ``both`` is a step whose result both submissions quote, so it appears under Track 1 —
#: where its alleles are argued — and its card names the other track.
TRACKS = {
    "track1": ("Track 1", ("track1", "both")),
    "track2": ("Track 2", ("track2",)),
}


def summary(iteration: str) -> str:
    """The iteration's own one-line description, with its docstring furniture taken off.

    The same sentence ``/api/steps`` serves in its ``index``, formatted the same way, so the
    page header and the iteration strip cannot describe the same iteration differently.
    """
    line = steps_module.summary(iteration).replace("``", "")
    _, separator, rest = line.partition("—")
    # A trailing "(docs/…/plan.md)" is a citation, right in a docstring and wrong in an <h1>.
    return re.sub(r"\s*\([^)]*\)$", "", (rest if separator else line).strip().rstrip("."))


def number(iteration: str) -> str:
    """``iteration2`` -> ``2``. The label a reader sees is the number, not the slug."""
    return "".join(c for c in iteration if c.isdigit())


def js(text: str) -> str:
    """A TypeScript single-quoted literal. Only quotes and backslashes need care; the
    generated file is Prettier-formatted afterwards like every other source file."""
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'").replace("\n", " ") + "'"


def steps_of(iteration: str, track: str) -> list[Step]:
    """One iteration's research steps for one track, in dependency order."""
    wanted = TRACKS[track][1]
    return [
        step
        for step in steps_module.steps_for(iteration)
        if step.kind != PLATFORM and step.track in wanted
    ]


def module(
    *, mid: str, path: str, label: str, title: str, parent: str, description: str, load: str
) -> str:
    """One `FeatureModule` literal, in the manifest's own shape."""
    return (
        "  {\n"
        f"    id: {js(mid)},\n"
        f"    path: {js(path)},\n"
        f"    navLabel: {js(label)},\n"
        f"    title: {js(title)},\n"
        "    group: 'decide',\n"
        f"    parent: {js(parent)},\n"
        f"    description: {js(description)},\n"
        f"    load: {load},\n"
        "  },\n"
    )


#: The banner every generated file opens with, so nobody edits one by hand.
BANNER = """/**
 * GENERATED by `uv run python tools/gen_steps_nav.py` from `mva.science.steps`.
 * Do not edit: declare the step in the step map and regenerate. `pnpm steps-nav:check`
 * fails the build when this file and the maps disagree.
 *
{what}
 */

"""


def render() -> str:
    """The navigation subtree: Track ▸ Iteration ▸ Step, in journey order."""
    what = (
        " * The research subtree of the manifest. Every label, title and description below is\n"
        " * a field of the step map or an iteration's own docstring line — nothing about a\n"
        " * step is written twice."
    )
    out = [
        BANNER.format(what=what),
        "import type { FeatureModule } from './types';\n\n",
        "export const STEP_MODULES: FeatureModule[] = [\n",
    ]
    for track, (track_label, _) in TRACKS.items():
        for iteration in steps_module.iterations():
            collected = steps_of(iteration, track)
            if not collected:
                continue
            label = f"Iteration {number(iteration)}"
            plural = "" if len(collected) == 1 else "s"
            out.append(
                module(
                    mid=f"{track}-{iteration}",
                    path=f"/{track}/{iteration}",
                    label=label,
                    title=f"{track_label}, {label.lower()} — {summary(iteration)}",
                    parent=track,
                    description=(
                        f"The {len(collected)} step{plural} of this iteration that argue "
                        f"{track_label}'s answer: each one's question, the claims filed before "
                        "the run, what became of them, the methodology entries they were "
                        "written in, and the figures they drew."
                    ),
                    load="() => import('../../pages/Iteration')",
                )
            )
            if track != "track1":
                continue
            out.extend(
                module(
                    mid=f"{track}-{iteration}-{step.slug}",
                    path=f"/{track}/{iteration}/{step.slug}",
                    label=f"Step {number(step.slug)}",
                    title=f"Step {number(step.slug)} — {step.title} ({label.lower()})",
                    parent=f"{track}-{iteration}",
                    description=step.goal,
                    load="() => import('../../pages/Step')",
                )
                for step in collected
            )
    out.append("];\n")
    return "".join(out)


def render_bodies() -> str:
    """The registry of analysis pages, keyed ``<iteration>/<slug>``."""
    what = (
        " * The deep analysis pages that exist for a step. A step with no entry here renders\n"
        " * its record alone — which is the whole truth about a step whose analysis page was\n"
        " * never built, and not a hole to apologise for."
    )
    rows = "".join(f"  {js(key)}: () => import('../{page}'),\n" for key, page in BODIES.items())
    return (
        BANNER.format(what=what)
        + "import type { ComponentType } from 'react';\n\n"
        + "export const STEP_BODIES: "
        + "Record<string, () => Promise<{ default: ComponentType }>> = {\n"
        + rows
        + "};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on drift instead of writing")
    args = parser.parse_args()

    written = {OUT: render(), OUT_BODIES: render_bodies()}
    if args.check:
        stale = [
            path
            for path, wanted in written.items()
            if (path.read_text(encoding="utf-8") if path.is_file() else "") != wanted
        ]
        if stale:
            names = ", ".join(str(path) for path in stale)
            print(f"gen_steps_nav: {names} stale — run `uv run python tools/gen_steps_nav.py`")
            return 1
        print(f"gen_steps_nav: up to date ({written[OUT].count('    id: ')} modules)")
        return 0
    for path, wanted in written.items():
        path.write_text(wanted, encoding="utf-8")
    print(f"gen_steps_nav: wrote {OUT} ({written[OUT].count('    id: ')} modules) and {OUT_BODIES}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
