"""The publish path: the coordinate guard, the bridge to a submission row, and the mirror.

The guard is the important one. The register is the surface where the data transfer
agreement gets broken by accident, because writing "chr15:40142000 A>G is causal" as a
hypothesis statement is the natural thing to type — and that sentence is patient data.
"""

import json

import pytest

from mva.pipeline import Annotation, DictAnnotator, Variant, rank_pairs
from mva.science import evidence_from_pair, to_row
from mva.science.dossier import Dossier, hypothesis_of
from mva.science.evidence import Direction, Evidence, weigh
from mva.science.export import COORDINATE, dossier_markdown, register, scan, write
from mva.science.hypothesis import Hypothesis, Status

CLAIM = dict(
    step="step-1",
    statement="The causal pair sits in BUB1B.",
    prediction="Two rare damaging alleles in BUB1B, one on each copy.",
    refuted_by="Both alleles turn out common in gnomAD.",
)


def dossier(**overrides) -> Dossier:
    """One assembled claim, built by hand — no database, no fixtures."""
    fields = {**CLAIM, **overrides}
    rows = tuple(fields.pop("evidence", ()))
    claim = Hypothesis(**fields, hypothesis_id="H001", gene="BUB1B")
    return Dossier(
        hypothesis=claim, history=(claim,), evidence=rows, weighing=weigh(list(rows), "H001")
    )


def observation(claim: str) -> Evidence:
    return Evidence(
        hypothesis_id="H001",
        direction=Direction.SUPPORTS,
        claim=claim,
        source_ref="methodology/003",
    )


# --- the coordinate guard ---------------------------------------------------------------


@pytest.mark.parametrize(
    "text",
    [
        "chr15:40142000 is the causal allele",
        "15:40142000 A>G",
        "chr15-40142000 sits in exon 3",
        "the variant at g.40142000A>G",
        "chrX:153000000 is unrelated",
    ],
)
def test_a_genomic_position_is_detected(text):
    assert COORDINATE.search(text), f"a position slipped through: {text!r}"


@pytest.mark.parametrize(
    "text",
    [
        "BUB1B is the strongest candidate",
        "gnomAD popmax AF below 1e-3",
        "the pair is compound heterozygous",
        "PMID:12345678 reports the same phenotype",
        "coverage dropped to 12x across exon 3",
        "ClinVar VCV000012345 is pathogenic",
    ],
)
def test_ordinary_scientific_prose_is_not_flagged(text):
    assert not COORDINATE.search(text), f"a false positive on: {text!r}"


def test_a_coordinate_in_a_statement_blocks_the_export(tmp_path):
    leaking = dossier(statement="chr15:40142000 A>G is one of the two alleles")
    leaks = scan([leaking])
    assert [leak.field for leak in leaks] == ["statement"]
    with pytest.raises(ValueError, match="refusing to export"):
        write([leaking], tmp_path)


def test_a_coordinate_in_an_evidence_claim_blocks_the_export(tmp_path):
    leaking = dossier(evidence=(observation("read depth 40 at chr15:40142000"),))
    assert [leak.field for leak in scan([leaking])] == ["evidence[0].claim"]
    with pytest.raises(ValueError, match="refusing to export"):
        write([leaking], tmp_path)


def test_every_leak_is_reported_at_once_not_one_at_a_time():
    """Being told about one leak six times is how people start deleting the check."""
    leaking = dossier(statement="chr15:40142000 A>G", refuted_by="unless 15:40143000 is common")
    assert len(scan([leaking])) == 2


def test_nothing_is_written_when_the_guard_fires(tmp_path):
    with pytest.raises(ValueError):
        write([dossier(statement="chr15:40142000 A>G")], tmp_path)
    assert not list(tmp_path.rglob("*.md"))
    assert not list(tmp_path.rglob("*.json"))


# --- the mirror --------------------------------------------------------------------------


def test_the_export_writes_a_dossier_a_board_and_a_register(tmp_path):
    written = write([dossier(evidence=(observation("BUB1B is depleted of LoF."),))], tmp_path)
    names = {path.name for path in written}
    assert "h001-bub1b.md" in names
    assert "README.md" in names
    assert (tmp_path / "science-register.json").exists()


def test_every_generated_file_says_it_was_generated(tmp_path):
    """A document that looks authored but was computed is trusted for the wrong reason."""
    for path in write([dossier()], tmp_path):
        if path.suffix == ".md":
            assert "Generated by `mva-science export`" in path.read_text()


def test_the_register_json_round_trips(tmp_path):
    write([dossier(evidence=(observation("BUB1B is depleted of LoF."),))], tmp_path)
    data = json.loads((tmp_path / "science-register.json").read_text())
    assert data["hypotheses"][0]["id"] == "H001"
    assert data["hypotheses"][0]["evidence"][0]["source_ref"] == "methodology/003"
    assert next(step["slug"] for step in data["steps"]) == "step-0"


def test_the_dossier_states_the_refutation_condition():
    text = dossier_markdown(dossier())
    assert "What would refute it" in text
    assert CLAIM["refuted_by"] in text


def test_the_dossier_warns_that_the_weighing_is_a_heuristic():
    assert "not a calibrated posterior" in dossier_markdown(dossier())


def test_an_untested_claim_says_so_rather_than_rendering_an_empty_table():
    assert "Nothing observed yet" in dossier_markdown(dossier())


def test_a_large_gap_between_committed_and_suggested_confidence_is_called_out():
    committed = dossier(evidence=(observation("Strong support."),))
    committed = Dossier(
        hypothesis=Hypothesis(
            **CLAIM,
            hypothesis_id="H001",
            gene="BUB1B",
            confidence=0.2,
            status=Status.TESTING,
            reasoning="Discounted: one weak source.",
        ),
        history=committed.history,
        evidence=committed.evidence,
        weighing=committed.weighing,
    )
    assert "differs from the suggestion" in dossier_markdown(committed)


def test_the_export_is_byte_stable_apart_from_its_timestamp(tmp_path):
    first = write([dossier()], tmp_path / "a")
    second = write([dossier()], tmp_path / "b")
    strip = lambda path: "\n".join(  # noqa: E731
        line for line in path.read_text().splitlines() if "Generated by" not in line
    )
    assert [strip(p) for p in first] == [strip(p) for p in second]


def test_the_register_records_the_suggested_confidence_beside_the_committed_one():
    data = register([dossier(evidence=(observation("Support."),))])
    entry = data["hypotheses"][0]
    assert entry["confidence"] is None
    assert entry["suggested_confidence"] > 0.5


# --- the bridge to submission -------------------------------------------------------------

LEFT = Variant("15", 40142000, "A", "G")
RIGHT = Variant("15", 40143000, "C", "T")

ANNOTATOR = DictAnnotator(
    {
        LEFT: Annotation(gene="BUB1B", consequence="stop_gained", gnomad_af=None),
        RIGHT: Annotation(gene="BUB1B", consequence="frameshift_variant", gnomad_af=1e-6),
    }
)


def ranked():
    return rank_pairs([(LEFT, RIGHT)], ANNOTATOR, gene_prior={"BUB1B": 2.0})[0]


def test_a_submission_row_names_the_claim_that_produced_it():
    row = to_row(ranked(), "H003", epcr=0.99)
    assert row.notes.startswith("H:H003")
    assert "BUB1B" in row.notes
    assert hypothesis_of(row) == "H003"


def test_a_row_naming_no_claim_reads_back_as_empty():
    from mva.pipeline import Row

    assert hypothesis_of(Row(variant=LEFT, notes="ACMG SF v3.2")) == ""


def test_the_pair_carries_the_arithmetic_that_ranked_it():
    """Without this, "why is this pair at rank 1" is answered by re-reading the code."""
    pair = ranked()
    assert pair.evidence is not None
    assert pair.evidence.both_loss_of_function
    assert pair.evidence.gene_prior == 2.0
    assert dict(pair.evidence.terms)["gene prior"] == 2.0


def test_the_ranking_arithmetic_becomes_sourced_evidence():
    rows = evidence_from_pair(ranked(), "H003", source_ref="methodology/018")
    assert rows, "a ranked pair with evidence must produce observations"
    assert all(row.source_ref == "methodology/018" for row in rows)
    assert all(row.hypothesis_id == "H003" for row in rows)
    assert any(row.direction is Direction.SUPPORTS for row in rows)


def test_the_gene_prior_is_recorded_as_a_stated_assumption_not_as_support():
    """A prior applied silently is an assumption buried in a threshold."""
    prior_rows = [
        row
        for row in evidence_from_pair(ranked(), "H003", "methodology/018")
        if "gene prior" in row.claim
    ]
    assert len(prior_rows) == 1
    assert prior_rows[0].direction is Direction.NEUTRAL
    assert prior_rows[0].strength == 0.0


def test_a_pair_with_no_recorded_arithmetic_yields_nothing_rather_than_a_guess():
    from mva.pipeline import RankedPair

    bare = RankedPair(LEFT, RIGHT, "BUB1B", 1.0)
    assert evidence_from_pair(bare, "H003", "methodology/018") == []


def test_a_common_pair_produces_refuting_evidence():
    common = DictAnnotator(
        {
            LEFT: Annotation(gene="BUB1B", consequence="missense_variant", gnomad_af=0.2),
            RIGHT: Annotation(gene="BUB1B", consequence="missense_variant", gnomad_af=0.3),
        }
    )
    pair = rank_pairs([(LEFT, RIGHT)], common)[0]
    rows = evidence_from_pair(pair, "H003", "methodology/018")
    assert any(row.direction is Direction.REFUTES for row in rows)


def test_a_claim_is_written_under_its_own_iteration_not_the_current_one(tmp_path):
    """Slugs restart at ``step-1`` every iteration.

    Resolving one against the *current* map would file an iteration-1 claim inside
    ``docs/iteration2/step-1/`` — wrong about where the work happened, and, while
    iteration 2 runs blind, a leak: iteration 1's candidate dossiers would appear inside
    iteration 2's folders before the unblinding entry exists.
    """
    write([dossier(iteration="iteration1", step="step-1")], root=tmp_path)

    assert (tmp_path / "iteration1" / "step-1" / "hypotheses" / "h001-bub1b.md").is_file()
    leaked = tmp_path / "iteration2" / "step-1" / "hypotheses" / "h001-bub1b.md"
    assert not leaked.exists(), "an iteration-1 claim was written into iteration 2's folder"


def test_a_dossier_prints_the_goal_of_its_own_iterations_step(tmp_path):
    """A frozen record must not be rewritten by the goals of work that came after it."""
    from mva.science import steps

    old = dossier(iteration="iteration1", step="step-1")
    assert old.step.goal == steps.by_slug("step-1", iteration="iteration1").goal
    assert old.step.goal != steps.by_slug("step-1", iteration="iteration2").goal
    assert old.step.goal in dossier_markdown(old)
