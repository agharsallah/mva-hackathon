/**
 * `local/no-raw-hex-color` — a hex colour literal may only appear in the generated ramps.
 *
 * CLAUDE.md: colour lives in one place. That place is now `tools/gen-theme.mjs`, which writes
 * `src/lib/palette/ramps.generated.ts` (hex, for Plotly/SVG) and `src/theme.generated.css`
 * (the matching `--color-*` custom properties). A hand-typed `#22c55e` anywhere else is a
 * colour that no longer has a name, a legend entry, or a Tailwind twin.
 *
 * Three shapes are checked, because a hex can hide in any of them:
 *   '#22c55e'                    string literal
 *   `bg-[${'#22c55e'}]`          template literal (quasis are not `Literal` nodes)
 *   style={{ color: '#22c55e' }} the same string literal, inside JSX — covered by the first
 *
 * The template-literal case is the one a naive `Literal`-only rule misses, which is why
 * eslint-rules/rules.test.js pins it with a negative test.
 */

const HEX_COLOR_RE = /#[0-9a-fA-F]{3,8}\b/;

const MESSAGE =
  'Raw hex colour literal. Colour comes from src/lib/palette (RAMP/C/TONE_MARK) for canvas ' +
  'and from a semantic Tailwind family (bg-good-950, text-broken-400) for the DOM. Both are ' +
  'generated by tools/gen-theme.mjs — add the shade there, do not type the number here.';

export default {
  meta: {
    type: 'problem',
    docs: {
      description:
        'disallow raw hex colour literals outside the generated palette (CLAUDE.md: colour lives in one place)',
    },
    schema: [],
    messages: { rawHex: MESSAGE },
  },
  create(context) {
    return {
      Literal(node) {
        if (typeof node.value === 'string' && HEX_COLOR_RE.test(node.value)) {
          context.report({ node, messageId: 'rawHex' });
        }
      },
      TemplateElement(node) {
        const text = node.value.cooked ?? node.value.raw;
        if (typeof text === 'string' && HEX_COLOR_RE.test(text)) {
          context.report({ node, messageId: 'rawHex' });
        }
      },
    };
  },
};
