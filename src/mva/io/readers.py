"""Parsers for the plain-text shapes command-line tools emit.

None of these know anything about one dataset or one challenge. They know about
*shapes*: a tab-separated table with a header and a couple of rollup lines glued to the
bottom, and a file cut into ``##``-delimited sections. Everything case-specific is
assembled a layer up.

That split is what makes the toolkit transfer: pointing it at a different dataset means
writing a new assembly layer, not a new parser.

Two conventions are shared across all of them:

* **A missing value is ``None``, never an exception.** These files are generated by shell
  pipelines and a truncated run must degrade to a gap in a chart, not a crash mid-report.
* **Nothing is coerced on read.** Values arrive as strings and become numbers only where a
  view asks for a number, because a column that is an integer in one case is a float or a
  sentinel in the next.
"""

from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path

Row = dict[str, str]


@dataclass(frozen=True)
class Table:
    """A tab-separated table, plus the odds and ends real ones carry.

    ``rows`` are the full-width records. ``scalars`` are the two-field rollup lines that
    tools habitually append underneath (``est_raw_coverage_x  51.9``), which would
    otherwise arrive as malformed rows. ``comments`` keeps the ``#`` provenance lines so a
    figure can cite how its own numbers were sampled.
    """

    columns: tuple[str, ...] = ()
    rows: list[Row] = field(default_factory=list)
    scalars: dict[str, str] = field(default_factory=dict)
    comments: list[str] = field(default_factory=list)

    def column(self, name: str) -> list[str]:
        """Every value in one column, in file order."""
        return [row[name] for row in self.rows if name in row]


@dataclass(frozen=True)
class Sections:
    """A file cut into named blocks by ``## <name>`` lines.

    ``blocks`` maps a section name to its ``(label, value)`` pairs; ``scalars`` holds the
    ``## <name><tab><value>`` lines that state a single figure rather than opening a block.
    """

    blocks: dict[str, list[tuple[str, str]]] = field(default_factory=dict)
    scalars: dict[str, str] = field(default_factory=dict)

    def counts(self, block: str) -> dict[str, int]:
        """One block as a label-to-count mapping, dropping cells that are not integers."""
        parsed = ((label, as_int(value)) for label, value in self.blocks.get(block, []))
        return {label: number for label, number in parsed if number is not None}


def read_table(path: str | Path) -> Table:
    """Read a header-first TSV, separating rollup scalars and ``#`` comments from rows."""
    columns: tuple[str, ...] = ()
    rows: list[Row] = []
    scalars: dict[str, str] = {}
    comments: list[str] = []

    for line in _lines(path):
        if line.startswith("#"):
            comments.append(line.lstrip("#").strip())
            continue
        cells = line.split("\t")
        if not columns:
            columns = tuple(cells)
            continue
        if len(cells) == len(columns):
            rows.append(dict(zip(columns, cells, strict=True)))
        elif len(cells) == 2:
            # A rollup line appended below the table proper — a total, not a record.
            scalars[cells[0]] = cells[1]
    return Table(columns, rows, scalars, comments)


def read_sections(path: str | Path) -> Sections:
    """Read a file cut into ``## name`` blocks of ``label<tab>value`` pairs."""
    blocks: dict[str, list[tuple[str, str]]] = {}
    scalars: dict[str, str] = {}
    current: list[tuple[str, str]] | None = None

    for line in _lines(path):
        if line.startswith("##"):
            head = line.lstrip("#").strip()
            if "\t" in head:
                # `## name<tab>value` states one figure; it does not open a block.
                name, _, value = head.partition("\t")
                scalars[name.strip()] = value.strip()
            else:
                current = blocks.setdefault(head, [])
            continue
        if current is None or "\t" not in line:
            continue
        label, _, value = line.partition("\t")
        current.append((label, value.strip()))
    return Sections(blocks, scalars)


def as_int(value: str | None) -> int | None:
    """Parse a whole number, returning ``None`` for anything that is not one."""
    try:
        return int(str(value).strip())
    except (TypeError, ValueError):
        return None


def as_float(value: str | None) -> float | None:
    """Parse a real number, returning ``None`` for anything that is not one."""
    try:
        return float(str(value).strip())
    except (TypeError, ValueError):
        return None


def _lines(path: str | Path, keep_blank: bool = False) -> Iterator[str]:
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    for raw in text.splitlines():
        line = raw.rstrip("\n").rstrip("\r")
        if line or keep_blank:
            yield line
