"""Run every Modal command through here, so the repo keeps a record of what ran on a GPU.

    uv run --group zoo-ml python tools/modal_trace.py deploy <lane>     # modal deploy -m ...
    uv run --group zoo-ml python tools/modal_trace.py run <lane> smoke  # modal run -m ...::smoke
    uv run --group zoo-ml python tools/modal_trace.py stop <lane>       # modal app stop
    uv run --group zoo-ml python tools/modal_trace.py stop-all          # every lane app
    uv run --group zoo-ml python tools/modal_trace.py summary           # the committed page

Each command appends one line to ``build/modal/trace.jsonl``: when it ran, the command, the
exit code, the seconds, and the output's last lines. ``summary`` writes a page from the
trace, the spend ledger (:mod:`sepiq.zoo.modal_budget`) and ``modal billing report``. That
page is committed; the trace and the ledger stay in ``build/``.

Why a wrapper rather than bare ``modal``: rented GPU time is spend, and spend that is not
recorded at the moment it happens is reconstructed later from a dashboard nobody can cite.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

from sepiq.zoo.modal_budget import Ledger, billing_report
from sepiq.zoo.modal_contract import APP_PREFIX, CAP_USD, LANE_BUDGET_USD, app_name

TRACE = Path("build/modal/trace.jsonl")
PAGE = Path("docs/modal-runs.md")


def _run(action: str, key: str, command: list[str]) -> int:
    started = time.time()
    done = subprocess.run(command, capture_output=True, text=True, check=False)
    output = (done.stdout + done.stderr).strip().splitlines()
    sys.stdout.write("\n".join(output) + "\n")
    row = {
        "ts": datetime.now(UTC).isoformat(timespec="seconds"),
        "action": action,
        "lane": key,
        "command": " ".join(command),
        "exit": done.returncode,
        "seconds": round(time.time() - started, 1),
        "tail": output[-6:],
    }
    TRACE.parent.mkdir(parents=True, exist_ok=True)
    with TRACE.open("a") as handle:
        handle.write(json.dumps(row) + "\n")
    return done.returncode


def _apps() -> list[str]:
    out = subprocess.run(
        ["modal", "app", "list", "--json"], capture_output=True, text=True, check=False
    )
    rows = json.loads(out.stdout or "[]")
    return [
        str(r.get("Description") or r.get("description") or "")
        for r in rows
        if str(r.get("State") or r.get("state") or "").startswith("deployed")
        or "ephemeral" in str(r.get("State") or r.get("state") or "")
    ]


def _summary() -> None:
    trace = [json.loads(x) for x in TRACE.read_text().splitlines()] if TRACE.exists() else []
    ledger = Ledger()
    lines = [
        "# Step 8 — what ran on Modal",
        "",
        (
            f"**Verified:** {datetime.now(UTC).date()} — generated by `tools/modal_trace.py "
            "summary` from `build/modal/trace.jsonl`, `build/modal/ledger.jsonl` and "
            "`modal billing report`. Do not edit; re-run the tool."
        ),
        "",
        (
            f"Cap **${CAP_USD:.2f}**; ledger total **${ledger.spent():.2f}** (GPU seconds × the "
            "published rate; excludes cold start and idle, which the billing report includes)."
        ),
        "",
        "## Spend per lane",
        "",
        "| lane | share | ledger $ | calls | items sent | scored | GPU s |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    rows = ledger.rows()
    for lane in sorted({r["model"] for r in rows} | set(LANE_BUDGET_USD)):
        mine = [r for r in rows if r["model"] == lane]
        lines.append(
            f"| {lane} | ${LANE_BUDGET_USD.get(lane, 0):.2f} | ${ledger.spent(lane):.3f} | "
            f"{len(mine)} | {sum(r['items'] for r in mine):,} | "
            f"{sum(r['scored'] for r in mine):,} | {sum(r['seconds'] for r in mine):,.0f} |"
        )
    try:
        billed = billing_report("this month")
        total = sum(float(r.get("cost", 0) or 0) for r in billed) if isinstance(billed, list) else 0
        lines += ["", f"**Modal billing report, this month:** ${total:.2f}"]
    except (subprocess.CalledProcessError, ValueError, FileNotFoundError) as error:
        lines += ["", f"Billing report unavailable: `{error}`"]
    lines += [
        "",
        "## Every Modal command, in order",
        "",
        "| when (UTC) | action | lane | exit | s | command |",
        "|---|---|---|---:|---:|---|",
    ]
    for r in trace:
        lines.append(
            f"| {r['ts']} | {r['action']} | {r['lane']} | {r['exit']} | {r['seconds']} "
            f"| `{r['command']}` |"
        )
    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text("\n".join(lines) + "\n")
    print(f"wrote {PAGE}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("action", choices=["deploy", "run", "stop", "stop-all", "summary"])
    parser.add_argument("lane", nargs="?", default="")
    parser.add_argument("extra", nargs=argparse.REMAINDER)
    args = parser.parse_args(argv)
    module = f"sepiq.zoo.modal_apps.{args.lane}"
    extra = [x for x in args.extra if x != "--"]
    if args.action == "deploy":
        return _run("deploy", args.lane, ["modal", "deploy", "-m", module])
    if args.action == "run":
        target = f"{module}::{extra[0]}" if extra else module
        return _run("run", args.lane, ["modal", "run", "-m", target, *extra[1:]])
    if args.action == "stop":
        return _run("stop", args.lane, ["modal", "app", "stop", "--yes", app_name(args.lane)])
    if args.action == "stop-all":
        code = 0
        for name in _apps():
            if name.startswith(APP_PREFIX):
                code |= _run(
                    "stop", name.removeprefix(APP_PREFIX), ["modal", "app", "stop", "--yes", name]
                )
        return code
    _summary()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
