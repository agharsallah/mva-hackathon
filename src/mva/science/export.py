"""The committed mirror: the register as Markdown and JSON, inside the repository.

The warehouse is the working copy — several people append to it, and it is where the CLI
reads and writes. But a reviewer cloning this repository has no database, and a judge
reading it has no credentials. So the register is exported into ``docs/<step>/`` as one
Markdown dossier per claim plus a machine-readable ``register.json``, and *that* is what
gets committed, reviewed in a diff, and cited by the report.

Two properties this file exists to guarantee:

**Nothing exported is mistaken for hand-written prose.** Every generated file opens with a
stamp naming the generator, the moment, and the row counts behind it. A document that looks
authored but was computed is a document people trust for the wrong reason.

**No patient coordinate crosses into git.** This is the one absolute rule in the repository
(:doc:`no patient data <notes/no-patient-data-in-the-repository>`), and the register is
exactly the surface where it would be broken by accident: it is natural to write "chr15:
40142000 A>G is the causal allele" as a hypothesis statement, and that sentence is patient
data. :func:`scan` refuses the export instead of trusting everyone to remember. Genes,
consequences, frequencies and reasoning are all fine — a *position* is not.
"""

import json
import re
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from . import steps
from .dossier import Dossier

#: Written into every generated file so it is never mistaken for prose someone wrote.
GENERATOR = "mva-science export"

#: What a genomic position looks like in free text, in the spellings that actually occur:
#: ``chr15:40142000``, ``15:40142000``, ``chr15-40142000``, ``g.40142000A>G``. The bar is
#: deliberately low — a false positive costs a rewording, a false negative costs the DTA.
COORDINATE = re.compile(
    r"""(?ix)
    (?: \b (?:chr)? (?:[1-9]|1\d|2[0-2]|[XYM]|MT) [:\-_] \d{4,} \b )
  | (?: \b g\. \d{4,} \s* [ACGT]+ \s* > \s* [ACGT]+ )
    """
)

#: Fields whose free text reaches the exported files and must therefore be scanned.
_SCANNED = ("statement", "prediction", "refuted_by", "reasoning")


@dataclass(frozen=True)
class Leak:
    """One place a genomic position would have entered the repository."""

    hypothesis_id: str
    field: str
    excerpt: str

    def __str__(self) -> str:
        return f"{self.hypothesis_id}.{self.field}: {self.excerpt!r}"


def scan(dossiers: list[Dossier]) -> list[Leak]:
    """Every genomic position that would be written into git by exporting these.

    Returns them rather than raising, so a caller can report all of them at once — being
    told about one leak at a time, six times, is how people start deleting the check.
    """
    leaks: list[Leak] = []
    for dossier in dossiers:
        texts = {field: getattr(dossier.hypothesis, field) for field in _SCANNED}
        for index, row in enumerate(dossier.evidence):
            texts[f"evidence[{index}].claim"] = row.claim
        for field, text in texts.items():
            leaks.extend(
                Leak(dossier.hypothesis.hypothesis_id, field, match.group(0))
                for match in COORDINATE.finditer(text or "")
            )
    return leaks


def _latest_recorded_at(dossiers: list[Dossier]) -> datetime | None:
    """The most recent moment the warehouse actually recorded behind these dossiers.

    ``None`` when nothing carries one (a :class:`Dossier` built by hand rather than read
    back from the warehouse) — callers fall back to :func:`datetime.now` only then.
    """
    stamps = [
        rec
        for dossier in dossiers
        for rec in (
            *(h.recorded_at for h in dossier.history),
            *(e.recorded_at for e in dossier.evidence),
        )
        if rec
    ]
    return datetime.fromisoformat(max(stamps)) if stamps else None


def _stamp(counts: str, dossiers: list[Dossier]) -> str:
    # A stamp of "now" would rewrite this line on every re-export even when nothing in
    # the warehouse changed — exactly the timestamp-only diff the project's standing rule
    # forbids. The latest `recorded_at` a revision or evidence row actually carries moves
    # only when something was actually appended, so re-exporting unchanged data is a no-op.
    moment = (_latest_recorded_at(dossiers) or datetime.now(UTC)).strftime("%Y-%m-%d %H:%M UTC")
    return (
        f"<!-- Generated by `{GENERATOR}` at {moment} from {counts}. "
        f"Do not edit: the warehouse is the working copy, this is its mirror. -->"
    )


def dossier_markdown(dossier: Dossier) -> str:
    """One claim as a reviewable document."""
    h = dossier.hypothesis
    stamp = _stamp(
        f"{len(dossier.history)} revisions and {len(dossier.evidence)} evidence rows", [dossier]
    )
    confidence = "not committed" if h.confidence is None else f"{h.confidence:.2f}"
    gap = dossier.confidence_gap

    lines = [
        f"# {h.hypothesis_id} — {h.statement}",
        "",
        stamp,
        "",
        f"**Step:** [{h.step}](../README.md) — {dossier.step.goal}",
        (
            f"**Status:** {h.status.value}  |  **Confidence:** {confidence}  |  "
            f"**Revisions:** {len(dossier.history)}"
        ),
        f"**Gene:** {h.gene or '—'}  |  **Path:** {h.path or '—'}",
        "",
        "## The claim",
        "",
        h.statement,
        "",
        "**Prediction if true.** " + h.prediction,
        "",
        "**What would refute it.** " + h.refuted_by,
        "",
    ]

    lines += ["## Evidence", ""]
    if dossier.evidence:
        lines += [
            "| # | Direction | Strength | Kind | Observation | Source |",
            "|---|---|---|---|---|---|",
        ]
        lines += [
            f"| {row.evidence_id} | {row.direction.value} | {row.strength:.2f} | "
            f"{row.kind} | {row.claim} | `{row.source_ref}` |"
            for row in dossier.evidence
        ]
    else:
        lines.append("Nothing observed yet. This claim is proposed, not tested.")
    lines.append("")

    lines += ["## Weighing", "", "```"]
    lines += dossier.weighing.arithmetic()
    lines += ["```", ""]
    lines.append(
        "The weighing is a transparent heuristic for triage, not a calibrated posterior: "
        "the strengths are human judgments, and rows drawn from the same underlying data "
        "are not independent the way the sum treats them."
    )
    if gap is not None and abs(gap) >= 0.15:
        lines += [
            "",
            (
                f"**The committed confidence differs from the suggestion by "
                f"{gap:+.2f}.** The reasoning below is why."
            ),
        ]
    lines.append("")

    lines += ["## History", "", "| Rev | Status | Confidence | Reasoning |", "|---|---|---|---|"]
    lines += [
        f"| {rev.revision} | {rev.status.value} | "
        f"{'—' if rev.confidence is None else f'{rev.confidence:.2f}'} | "
        f"{rev.reasoning or '—'} |"
        for rev in dossier.history
    ]
    lines.append("")
    return "\n".join(lines)


def board_markdown(dossiers: list[Dossier], step: steps.Step) -> str:
    """The index over one step's claims."""
    stamp = _stamp(f"{len(dossiers)} hypotheses", dossiers)
    lines = [
        f"# {step.title} — hypothesis board",
        "",
        stamp,
        "",
        f"**Goal.** {step.goal}",
        "",
    ]
    if not dossiers:
        lines += ["No hypotheses recorded for this step yet.", ""]
        return "\n".join(lines)

    lines += ["| ID | Status | Confidence | Gene | Evidence | Claim |", "|---|---|---|---|---|---|"]
    for dossier in dossiers:
        h = dossier.hypothesis
        lines.append(
            f"| [{h.hypothesis_id}]({dossier.slug}.md) | {h.status.value} | "
            f"{'—' if h.confidence is None else f'{h.confidence:.2f}'} | "
            f"{h.gene or '—'} | "
            f"{len(dossier.supports)}+ / {len(dossier.refutes)}− | {h.statement} |"
        )
    lines.append("")
    return "\n".join(lines)


def register(dossiers: list[Dossier]) -> dict:
    """The whole register as plain data — what a downstream tool reads."""
    moment = _latest_recorded_at(dossiers) or datetime.now(UTC)
    return {
        "generator": GENERATOR,
        "generated_at": moment.isoformat(timespec="seconds"),
        "steps": [
            {
                "slug": s.slug,
                "title": s.title,
                "goal": s.goal,
                "kind": s.kind,
                "status": s.status,
                "unblocks": list(s.unblocks),
            }
            for s in steps.STEPS
        ],
        "hypotheses": [
            {
                "id": d.hypothesis.hypothesis_id,
                "step": d.hypothesis.step,
                "statement": d.hypothesis.statement,
                "prediction": d.hypothesis.prediction,
                "refuted_by": d.hypothesis.refuted_by,
                "gene": d.hypothesis.gene,
                "path": d.hypothesis.path,
                "status": d.hypothesis.status.value,
                "confidence": d.hypothesis.confidence,
                "suggested_confidence": round(d.weighing.confidence, 4),
                "revisions": len(d.history),
                "evidence": [
                    {
                        "id": e.evidence_id,
                        "direction": e.direction.value,
                        "strength": e.strength,
                        "kind": e.kind,
                        "claim": e.claim,
                        "source_ref": e.source_ref,
                        "lineage_ref": e.lineage_ref,
                    }
                    for e in d.evidence
                ],
            }
            for d in dossiers
        ],
    }


def write(dossiers: list[Dossier], root: str | Path = "docs") -> list[Path]:
    """Write the mirror and return the paths written.

    Refuses outright if any text carries a genomic position. The check is not advisory:
    an export that leaks one coordinate has broken the data transfer agreement, and the
    cost of that is not proportionate to the convenience of skipping it.
    """
    leaks = scan(dossiers)
    if leaks:
        raise ValueError(
            "refusing to export: genomic positions would enter the repository.\n  "
            + "\n  ".join(str(leak) for leak in leaks)
            + "\nReword to name the gene and the consequence, never the position."
        )

    base = Path(root)
    written: list[Path] = []
    # Keyed by *iteration and* slug. Slugs restart at ``step-1`` each iteration, so
    # grouping by slug alone would write an iteration-1 claim into the current
    # iteration's folder - which is both wrong about where the work happened and, while
    # iteration 2 runs blind, a leak: it would put iteration 1's candidate dossiers
    # inside ``docs/iteration2/step-*/`` before the unblinding entry exists.
    by_step: dict[tuple[str, str], list[Dossier]] = {}
    for dossier in dossiers:
        claim = dossier.hypothesis
        by_step.setdefault((claim.filed_under, claim.step), []).append(dossier)

    for iteration in steps.iterations():
        for step in steps.steps_for(iteration):
            if not step.takes_hypotheses:
                continue
            group = by_step.get((iteration, step.slug), [])
            if not group and not (base / step.folder).exists():
                continue
            folder = base / step.folder / "hypotheses"
            folder.mkdir(parents=True, exist_ok=True)

            index = folder / "README.md"
            index.write_text(board_markdown(group, step) + "\n", encoding="utf-8")
            written.append(index)

            for dossier in group:
                path = folder / f"{dossier.slug}.md"
                path.write_text(dossier_markdown(dossier) + "\n", encoding="utf-8")
                written.append(path)

    registry = base / "science-register.json"
    registry.write_text(json.dumps(register(dossiers), indent=2) + "\n", encoding="utf-8")
    written.append(registry)
    return written
