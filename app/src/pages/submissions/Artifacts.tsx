import { API_URL } from '../../api/client';
import type { Deliverable, SubmissionIteration } from '../../api/types';
import { Badge } from '../../components/Badge';
import { type Column, DataTable } from '../../components/DataTable';
import { Chip, Exhibit } from '../../components/Exhibit';
import { FigureLightbox } from '../../components/FigureLightbox';
import { bytes as fmtBytes, iso } from '../../lib/format';
import type { Tone } from '../../lib/palette';
import { C } from '../../lib/palette';
import { useUrlState } from '../../lib/urlstate';
import { blobUrl, figureDirs } from './iteration';

/**
 * What is in the folder, and what came out of it.
 *
 * The four files the organisers actually receive are marked; everything else is material a
 * judge needs to check them. The figures are the ones the report cites — each regenerated by
 * the script that drew it, never by hand — and are served by the API rather than bundled, so
 * this page shows the same PNG or SVG the report embeds.
 */

/** One address that opens this exact figure — the citation "copy link" hands over. */
function figureLink(slug: string): string {
  const params = new URLSearchParams(window.location.search);
  params.set('figure', slug);
  return `${window.location.origin}${window.location.pathname}?${params}`;
}

/** Green marks a file the organisers receive; blue is supporting material. */
const KIND_TONE: Record<Deliverable['kind'], Tone> = {
  readme: 'machinery',
  'report-md': 'machinery',
  'report-pdf': 'good',
  'methods-json': 'machinery',
  'methods-xlsx': 'good',
  'decode-table': 'machinery',
  selectors: 'machinery',
  other: 'neutral',
};

const UPLOADED = new Set<Deliverable['kind']>(['report-pdf', 'methods-xlsx']);

export function Artifacts({
  iteration,
  source,
}: {
  iteration: SubmissionIteration;
  source?: string;
}) {
  const slugs = iteration.figures.map((f) => f.slug);
  const [openFigure, setOpenFigure] = useUrlState('figure', '', slugs);

  const columns: Column<Deliverable>[] = [
    {
      key: 'name',
      header: 'file',
      render: (d) => (
        <a
          href={blobUrl(`${iteration.folder}/${d.name}`)}
          className="font-mono text-chrome-100 underline decoration-chrome-700 underline-offset-2 hover:text-chrome-50"
        >
          {d.name}
        </a>
      ),
    },
    {
      key: 'kind',
      header: 'kind',
      render: (d) => (
        <Badge
          tone={KIND_TONE[d.kind]}
          title={UPLOADED.has(d.kind) ? 'uploaded to the organisers' : 'supporting material'}
        >
          {d.kind}
        </Badge>
      ),
    },
    { key: 'bytes', header: 'size', align: 'right', render: (d) => fmtBytes(d.bytes) },
    {
      key: 'modified',
      header: 'modified',
      render: (d) => (
        <span className="font-mono text-micro text-chrome-400">{iso(d.modified)}</span>
      ),
    },
  ];

  return (
    <Exhibit
      title="Deliverables and figures"
      legend={
        <>
          <Chip color={C.good}>green = uploaded</Chip> — the rendered report and the filled methods
          form, the two files that leave this repository alongside the (uncommitted) CSV.{' '}
          <Chip color={C.machinery}>blue = supporting material</Chip> — the sources those were
          rendered from, kept so a reviewer can rebuild them. The figures below are the ones the
          report cites, committed under{' '}
          <span className="font-mono">
            {figureDirs(iteration.figures.map((f) => f.path)).join(', ') ||
              `figures/${iteration.track}/`}
          </span>{' '}
          and served by the API from the same bytes the report embeds. Click a figure to open it
          full size — the open figure is written to the address bar as{' '}
          <span className="font-mono">?figure=&lt;slug&gt;</span>, so one link cites one figure.
        </>
      }
      reading="An iteration folder is frozen once uploaded, so the size and modification time of each file are part of the record: they say which bytes were current when the folder was closed."
      data={iteration.deliverables}
      source={source}
    >
      <div className="space-y-4">
        <DataTable
          rows={iteration.deliverables}
          columns={columns}
          rowKey={(d) => d.name}
          empty="no file in this folder"
        />

        {iteration.figures.length > 0 && (
          <ul className="grid gap-3 md:grid-cols-2 xl:grid-cols-3">
            {iteration.figures.map((f) => (
              <li key={f.slug} className="space-y-1 rounded-card border border-line bg-well p-2">
                <button
                  type="button"
                  onClick={() => setOpenFigure(f.slug)}
                  aria-label={`open figure ${f.slug}`}
                  className="block w-full cursor-zoom-in focus:outline-none focus-visible:ring-1 focus-visible:ring-focus"
                >
                  <img
                    src={f.url.startsWith('/') ? `${API_URL}${f.url}` : f.url}
                    alt={f.slug.replace(/[-_]/g, ' ')}
                    loading="lazy"
                    className="w-full rounded-control border border-line-soft"
                  />
                </button>
                <div className="font-mono text-micro break-all text-chrome-400">{f.path}</div>
              </li>
            ))}
          </ul>
        )}

        <FigureLightbox
          figures={iteration.figures}
          slug={openFigure || null}
          onSelect={(next) => setOpenFigure(next ?? '')}
          linkFor={figureLink}
        />
      </div>
    </Exhibit>
  );
}
